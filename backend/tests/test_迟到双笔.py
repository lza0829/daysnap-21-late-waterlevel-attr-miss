"""双笔迟到夹具：首抽后连补两笔同日流水。

架构口径=基镜+纠偏版本链。
- 户甲（盖写口径人格）：主读（当前镜）只剩最新盖写，第二笔迟到后读不回第一笔前的旧有效行。
- 户乙（版本链人格）：基线/链接口可沿链回看 v1→v2→v3，第二笔迟到后仍能读出第一笔迟到前旧余额。
两口径在“旧有效余额可否回看”上必须给出可区分结果（本测试显式断言分叉）。
"""

from app.db import 连接
from app.services import 迟到补抽, 回放, 抽取, 装载

日 = "2026-11-20"


def _双笔迟到场景():
    装载.装载流水(
        [
            {"流水号": "甲-基1", "账户键": "户甲", "营业日": 日, "变动额": 10000},
            {"流水号": "甲-基2", "账户键": "户甲", "营业日": 日, "变动额": -2500},
            {"流水号": "乙-基1", "账户键": "户乙", "营业日": 日, "变动额": 5000},
        ],
        "批-基线",
    )
    抽取.日终抽取(日, "抽-v1")
    
    装载.装载流水(
        [{"流水号": "甲-迟1", "账户键": "户甲", "营业日": 日, "变动额": 2000}],
        "批-迟到一",
    )
    抽取.日终抽取(日, "抽-v2")
    
    装载.装载流水(
        [{"流水号": "甲-迟2", "账户键": "户甲", "营业日": 日, "变动额": 3000}],
        "批-迟到二",
    )
    抽取.日终抽取(日, "抽-v3")


def test_两笔迟到均有处置证据且状态闭合(库):
    _双笔迟到场景()
    conn = 连接()
    try:
        单们 = 迟到补抽.列处置单(conn, 营业日=日, 账户键="户甲")
        assert len(单们) == 2, "每笔迟到必须有独立处置单，禁止静默忽略"
        assert {s["流水号"] for s in 单们} == {"甲-迟1", "甲-迟2"}
        assert all(s["状态"] == "已纠偏" and s["valid"] == 1 for s in 单们)
        
        按号 = {s["流水号"]: s for s in 单们}
        assert 按号["甲-迟1"]["级联"] == 0
        assert 按号["甲-迟2"]["级联"] == 1
        assert 按号["甲-迟1"]["前余额"] == 7500
        assert 按号["甲-迟1"]["后余额"] == 9500
        assert 按号["甲-迟2"]["前余额"] == 9500
        assert 按号["甲-迟2"]["后余额"] == 12500
    finally:
        conn.close()


def test_甲人格_主读只有最新盖写_旧有效行不可主读(库):
    _双笔迟到场景()
    conn = 连接()
    try:
        当前 = 迟到补抽.读镜(conn, "户甲", 日, "当前")
        assert 当前["镜"]["版本号"] == 3
        assert 当前["镜"]["余额"] == 12500
        
        主读 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 周期快照 WHERE 账户键=? AND 营业日=? "
                "AND 状态='有效' AND 是否当前=1",
                ("户甲", 日),
            )
        ]
        assert len(主读) == 1
        assert 主读[0]["余额"] == 12500
        旧余额们 = {r["余额"] for r in conn.execute(
            "SELECT 余额 FROM 周期快照 WHERE 账户键=? AND 营业日=? "
            "AND 状态='有效' AND 是否当前=1 AND 余额 IN (7500, 9500)",
            ("户甲", 日),
        )}
        assert 旧余额们 == set(), "盖写人格：主读不得回看第一笔迟到前的旧有效余额"
    finally:
        conn.close()


def test_乙人格_版本链可回看第一笔迟到前旧余额(库):
    _双笔迟到场景()
    conn = 连接()
    try:
        基线 = 迟到补抽.读镜(conn, "户甲", 日, "基线")
        assert 基线["镜"]["版本号"] == 1
        
        assert 基线["镜"]["余额"] == 7500
        链 = 迟到补抽.读镜(conn, "户甲", 日, "链")
        assert [(v["版本号"], v["余额"], v["是否当前"]) for v in 链["链"]] == [
            (1, 7500, 0),
            (2, 9500, 0),
            (3, 12500, 1),
        ]
        
        assert 基线["镜"]["抽取批次编号"] == "抽-v1"
        assert 基线["镜"]["快照键"] == "户甲|2026-11-20"
    finally:
        conn.close()


def test_口径可区分_回看能力分叉(库):
    """同一数据下：主读不可回看 vs 链接口可回看，两口径结果必须可区分。"""
    _双笔迟到场景()
    conn = 连接()
    try:
        主读余额 = {
            r["余额"]
            for r in conn.execute(
                "SELECT 余额 FROM 周期快照 WHERE 账户键=? AND 营业日=? "
                "AND 状态='有效' AND 是否当前=1",
                ("户甲", 日),
            )
        }
        链上余额 = {v["余额"] for v in 迟到补抽.读镜(conn, "户甲", 日, "链")["链"]}
        assert 主读余额 == {12500}
        assert 链上余额 == {7500, 9500, 12500}
        assert 主读余额 != 链上余额, "盖写主读与版本链回看必须可区分"
    finally:
        conn.close()


