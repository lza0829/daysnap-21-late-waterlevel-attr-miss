def test_双笔迟到JSON夹具_端到端(库):
    """任务夹具：先抽再补两笔同日流水，必须落处置实体、版本链，并保持回放守恒。"""
    import json
    from pathlib import Path

    夹具根 = Path(__file__).resolve().parent.parent.parent / "fixtures"

    def 装(名):
        数据 = json.loads((夹具根 / 名).read_text(encoding="utf-8"))
        return 装载.装载流水(数据["流水"], 数据["批次编号"])

    装("迟到双笔_基线.json")
    抽取.日终抽取(日, "夹具-抽-v1")
    报一 = 装("迟到双笔_迟到一.json")
    assert 报一["迟到待处置"] == 1
    抽取.日终抽取(日, "夹具-抽-v2")
    报二 = 装("迟到双笔_迟到二.json")
    assert 报二["迟到待处置"] == 1
    抽取.日终抽取(日, "夹具-抽-v3")

    conn = 连接()
    try:
        链 = 迟到补抽.读镜(conn, "户甲", 日, "链")
        assert [v["余额"] for v in 链["链"]] == [7500, 9500, 12500]
        基线 = 迟到补抽.读镜(conn, "户甲", 日, "基线")
        
        assert 基线["镜"]["余额"] == 7500
        assert len(迟到补抽.列处置单(conn, 账户键="户甲")) == 2
    finally:
        conn.close()
    assert 回放.回放核对(日, "夹具-回放")["通过"] is True


def test_待处置在补抽前可观测_不静默(库):
    """迟到入账后、补抽前，处置单处于待处置且可只读观测。"""
    装载.装载流水(
        [{"流水号": "乙-基", "账户键": "户乙", "营业日": 日, "变动额": 5000}],
        "批-基",
    )
    抽取.日终抽取(日, "抽-1")
    装载.装载流水(
        [{"流水号": "乙-迟", "账户键": "户乙", "营业日": 日, "变动额": 1100}],
        "批-迟",
    )
    conn = 连接()
    try:
        待 = 迟到补抽.列处置单(conn, 状态="待处置")
        assert len(待) == 1 and 待[0]["流水号"] == "乙-迟"
        assert 待[0]["valid"] == 1
    finally:
        conn.close()
    抽取.日终抽取(日, "抽-补")
    conn = 连接()
    try:
        assert all(s["状态"] == "已纠偏" for s in 迟到补抽.列处置单(conn))
    finally:
        conn.close()
